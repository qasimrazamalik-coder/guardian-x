import { motion } from 'framer-motion'
import { Bot, Download, Link2, Send, Sparkles, Trash2 } from 'lucide-react'
import { useEffect, useRef, useState } from 'react'
import { Card, Eyebrow } from '../components/ui'
import { call, on } from '../lib/bridge'
import type { AssistantStatus, McpInfo } from '../lib/types'

interface Msg { role: 'user' | 'bot'; text: string; sources?: string[]; done?: boolean }

const suggestions = [
  "Why shouldn't I keep it plugged in all the time?",
  'What caused my biggest battery drop?',
  'Which apps are draining my battery?',
  'How do I set up the 80% limit with a Tapo plug?',
]

export function Assistant() {
  const [status, setStatus] = useState<AssistantStatus | null>(null)
  const [mcp, setMcp] = useState<McpInfo | null>(null)
  const [msgs, setMsgs] = useState<Msg[]>([])
  const [input, setInput] = useState('')
  const [busy, setBusy] = useState(false)
  const [setup, setSetup] = useState<{ stage: string; progress: number } | null>(null)
  const scroller = useRef<HTMLDivElement>(null)
  const current = useRef<number>(0)

  const load = () => { call<AssistantStatus>('assistantStatus').then(setStatus); call<McpInfo>('mcpInfo').then(setMcp) }
  useEffect(() => {
    load()
    const off1 = on('chat', (e) => {
      if (e.id !== current.current) return
      setMsgs((m) => {
        const copy = [...m]
        const last = { ...copy[copy.length - 1] }
        if (e.delta) last.text += e.delta
        if (e.error) { last.text += (last.text ? '\n\n' : '') + '⚠ ' + e.error; last.done = true; setBusy(false) }
        if (e.done) { last.done = true; last.sources = e.sources; setBusy(false) }
        copy[copy.length - 1] = last
        return copy
      })
    })
    const off2 = on('setup', (e) => { setSetup(e.done ? null : e); if (e.done) load() })
    return () => { off1(); off2() }
  }, [])
  useEffect(() => { scroller.current?.scrollTo({ top: scroller.current.scrollHeight, behavior: 'smooth' }) }, [msgs])

  const ready = status?.running && status.chatModelReady
  const ask = async (q: string) => {
    if (!q.trim() || busy) return
    const id = Date.now()
    current.current = id
    setMsgs((m) => [...m, { role: 'user', text: q }, { role: 'bot', text: '' }])
    setInput('')
    setBusy(true)
    try { await call('ask', { id, question: q }) } catch (e: any) {
      setMsgs((m) => { const c = [...m]; c[c.length - 1] = { role: 'bot', text: '⚠ ' + e.message, done: true }; return c }); setBusy(false)
    }
  }

  return (
    <div className="grid" style={{ gridTemplateColumns: '1fr 320px', alignItems: 'start', height: '100%' }}>
      <Card glow style={{ display: 'flex', flexDirection: 'column', minHeight: 560 }}>
        <div className="row" style={{ justifyContent: 'space-between' }}>
          <Eyebrow dot={ready ? 'var(--mint)' : 'var(--amber)'}><Bot size={13} /> Guardian assistant · local · {status?.chatModel}</Eyebrow>
          {msgs.length > 0 && <button className="btn" style={{ padding: '6px 10px', marginBottom: 12 }} onClick={() => { setMsgs([]); call('assistantReset') }}><Trash2 size={13} /> New chat</button>}
        </div>
        <div ref={scroller} className="chat" style={{ flex: 1, overflowY: 'auto', padding: '6px 2px 16px', maxHeight: 'calc(100vh - 290px)' }}>
          {msgs.length === 0 && (
            <div style={{ textAlign: 'center', padding: '50px 20px' }}>
              <motion.div animate={{ rotate: [0, 8, -8, 0] }} transition={{ duration: 6, repeat: Infinity }} style={{ display: 'inline-block', color: 'var(--mint)' }}><Sparkles size={34} /></motion.div>
              <div style={{ fontSize: 20, fontWeight: 600, marginTop: 12 }}>Ask about your battery</div>
              <div className="body" style={{ maxWidth: 460, margin: '8px auto 22px' }}>Answers come from your own Guardian X data and its battery knowledge base, generated by a model running on your laptop. Nothing leaves this PC.</div>
              <div style={{ display: 'flex', flexWrap: 'wrap', gap: 10, justifyContent: 'center' }}>
                {suggestions.map((s) => <button key={s} className="btn" disabled={!ready} onClick={() => ask(s)}>{s}</button>)}
              </div>
            </div>
          )}
          {msgs.map((m, i) => (
            <motion.div key={i} className={`msg ${m.role}`} initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }}>
              {m.text}{m.role === 'bot' && !m.done && <span className="caret" />}
              {m.sources && m.sources.length > 0 && (
                <div style={{ marginTop: 10, display: 'flex', flexWrap: 'wrap', gap: 6 }}>
                  {m.sources.map((s, k) => <span key={k} className="source">[K{k + 1}] {s}</span>)}
                </div>
              )}
            </motion.div>
          ))}
        </div>
        <form onSubmit={(e) => { e.preventDefault(); ask(input) }} className="row" style={{ gap: 10 }}>
          <input className="input" placeholder={ready ? 'Ask anything about your battery, charging or apps…' : 'Set up the local AI engine to start chatting'} value={input} disabled={!ready} onChange={(e) => setInput(e.target.value)} />
          <button className="btn primary" disabled={!ready || busy || !input.trim()}><Send size={15} /></button>
        </form>
      </Card>

      <div className="grid">
        <Card delay={0.05}>
          <Eyebrow dot={ready ? 'var(--mint)' : 'var(--amber)'}>Local AI engine</Eyebrow>
          {status && (
            <div className="grid" style={{ gap: 8 }}>
              <Row k="Ollama" v={status.installed ? (status.running ? 'running' : 'installed') : 'not installed'} ok={status.running} />
              <Row k={status.chatModel} v={status.chatModelReady ? 'ready' : 'missing'} ok={status.chatModelReady} />
              <Row k={status.embedModel} v={status.embedModelReady ? 'ready' : 'missing'} ok={status.embedModelReady} />
              <div className="body" style={{ fontSize: 12 }}>Models stored in {status.modelsFolder}</div>
            </div>
          )}
          {setup ? (
            <div style={{ marginTop: 14 }}>
              <div className="body" style={{ fontSize: 12.5 }}>{setup.stage}</div>
              <div className="bar" style={{ marginTop: 8 }}><motion.i animate={{ width: setup.progress >= 0 ? `${setup.progress * 100}%` : '40%' }} /></div>
            </div>
          ) : !ready && (
            <button className="btn primary" style={{ marginTop: 14, width: '100%', justifyContent: 'center' }} onClick={() => call('assistantSetup')}>
              <Download size={15} /> Set up (about 5 GB)
            </button>
          )}
          <div className="body" style={{ fontSize: 12, marginTop: 12 }}>Uses Ollama with {status?.chatModel} for answers and {status?.embedModel} for search. Runs on your RTX GPU; free and offline.</div>
        </Card>
        <Card delay={0.1}>
          <Eyebrow><Link2 size={13} /> MCP server</Eyebrow>
          <div className="body" style={{ fontSize: 13 }}>Lets Claude read your Guardian X data (battery, history, apps, storage, modes) through read-only tools.</div>
          <button className="btn" style={{ marginTop: 12, width: '100%', justifyContent: 'center' }} disabled={mcp?.connected}
            onClick={async () => { await call('mcpConnect'); load() }}>{mcp?.connected ? 'Connected to Claude Desktop' : 'Connect to Claude Desktop'}</button>
          <div className="num" style={{ fontSize: 10.5, color: 'var(--faint)', marginTop: 10, wordBreak: 'break-all', userSelect: 'text' }}>{mcp?.exePath}</div>
          {mcp?.connected && <div className="body" style={{ fontSize: 12, marginTop: 8 }}>Restart Claude Desktop to load it.</div>}
        </Card>
      </div>
    </div>
  )
}

function Row({ k, v, ok }: { k: string; v: string; ok: boolean }) {
  return <div className="row" style={{ justifyContent: 'space-between' }}><span className="num" style={{ fontSize: 12.5 }}>{k}</span><span className="num" style={{ fontSize: 12, color: ok ? 'var(--mint)' : 'var(--amber)' }}>{v}</span></div>
}
